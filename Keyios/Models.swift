import Foundation

/// 一条摘要 = 从一级节点里挑出来做预览的内容：时间 + 文本。
///
/// `struct` 在 Swift 里是"值类型"（像 C 的 struct，赋值即拷贝）。
/// `Identifiable` 是让 SwiftUI 的列表能区分"这是第几条"——它要求有个 `id`。
struct Summary: Identifiable, Hashable {
    let id = UUID()      // UUID = 唯一标识符，每 new 一次都不一样
    let time: String     // "10:12"
    let text: String     // "买菜"
}

/// 列表里的一行 = 一个 dog 文件（一篇日记）。
struct DiaryEntry: Identifiable, Hashable {
    let id = UUID()

    /// 文件名还原出的 root 文本，如 "2026-10-11 日记"
    ///
    /// 注意：**dog 格式里 root 文本就存在文件名上**，文件内容里没有这一行。
    /// 磁盘上空格会转成下划线（`2026-10-11_日记.dog`），那层转换属于文件 IO，
    /// 这里是内存形态，所以带空格。
    let fileName: String

    /// 最多取 3 条（列表面板只画 3 条）
    let summaries: [Summary]
}

// ============================================================================
// 假数据 —— MVP 阶段先不碰 dog 解析
// ============================================================================
// 日期一律按"距今天几天"算，这样无论哪天跑，缩减规则的结果都对得上。
// 够铺满一屏多（iPhone 一屏大概 15 行）。
// ============================================================================

/// 造一个"N 天前"的文件名，如 `day(3)` -> "2026-10-12 日记"
private func day(_ daysAgo: Int) -> String {
    let d = Calendar.current.date(byAdding: .day, value: -daysAgo, to: Date())!
    let f = DateFormatter()
    f.dateFormat = "yyyy-MM-dd"          // 磁盘上的 dog 文件名格式
    return f.string(from: d) + " 日记"   // "日记"二字是规则里要吃掉的那部分
}

