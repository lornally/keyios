// ============================================================================
// 【内存里的日记表】—— 数据长什么样 (见 p1列表.md)
// ============================================================================
// 数据的真身是"遍历 iCloud 目录": 读到的是一堆**文件名**, 所以内存里就组织成
// "文件名 -> 那一篇"的字典 (key = 磁盘上的文件名, 见 设计/dog格式.md)。
//
// 两个别搞错的地方:
//   1. 字典是**无序**的 —— 列表要的顺序是显示的时候现排的, 不是数据自带的
//   2. 文件名不一定带日期, 也不一定带"日记"二字 (比如 "摩托车") ——
//      所以日期不是字段, 是从文件名里**解**出来的 (见 f1文件名.swift)
// ============================================================================

/// 一篇日记在内存里的样子 —— 列表页只需要这些。
struct 日记: Identifiable, Hashable {

  /// 磁盘上的文件名 (不含 .dog), 比如 "26-10-16_日记"。
  /// 它同时是字典的 key, 所以自己就是身份 —— 不用 UUID, 重新读一遍目录也不会变。
  let 文件名: String

  /// 一级节点的**原始文本** —— 前缀/正文/尾缀都没拆
  /// (拆是以后 dog 解析器的事, 见 设计/dog格式细节.md)。
  /// 最多 3 条: 列表面板只画 3 条, 见 设计/mvp.md
  let 摘要: [String]

  /// Identifiable要求的标识,
  /// 这里就是getter只读计算属性, 现在的写法是“零成本的别名”：值仍然只有一份，就在 文件名 里。
  var id: String { 文件名 }
}
