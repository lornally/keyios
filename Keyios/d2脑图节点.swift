// ============================================================================
// 【脑图节点】—— 详情页要画的数据
// ============================================================================
// 由 f3解析dog 从 .dog 文本造 (rules: 设计/dog格式细节.md §6).
// ============================================================================

struct 脑图节点: Identifiable, Equatable, Sendable {

  /// 稳定身份: 折叠、编辑焦点都认它。改正文不会变, 所以别拿正文当 id。
  let id: String

  /// 行首时间戳(如 "08:30"), 显示成灰色; 没有就是 nil。
  var 时间: String? = nil

  /// 正文 —— 显示和编辑的都是它。
  var 正文: String

  /// 行尾图标词(ing / todo / done / !!), 显示成小胶囊; 没有就是 nil。
  var 图标: String? = nil

  /// 儿子, 按显示顺序。
  var 子: [脑图节点] = []

  var 有子: Bool { !子.isEmpty }

  /// 折叠徽上的 "+N": 所有子孙的数量。
  var 后代数: Int { 子.reduce(0) { $0 + 1 + $1.后代数 } }
}
