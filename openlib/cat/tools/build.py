"""cat 多语言数据包生成器: keywords.yaml + macos.yaml → python/swift 数据文件.

用法: python3 tools/build.py   (需要 pyyaml)
生成物: python/cat/_data.py, swift/Sources/Cat/Data.swift
"""

import os

import yaml


_根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _查重复(节点):
    if isinstance(节点, yaml.MappingNode):
        键们 = set()
        for 键, 值 in 节点.value:
            if 键.value in 键们:
                raise ValueError(f"重复 key {键.value!r}")
            键们.add(键.value)
            _查重复(值)
    elif isinstance(节点, yaml.SequenceNode):
        for 项 in 节点.value:
            _查重复(项)


def _读yaml(名):
    with open(os.path.join(_根, 名), encoding="utf-8") as f:
        文本 = f.read()
    _查重复(yaml.compose(文本))
    表 = yaml.safe_load(文本)
    if not isinstance(表, dict) or not all(isinstance(k, str) and isinstance(v, str) for k, v in 表.items()):
        raise ValueError(f"{名}: 必须是 字符串→字符串 映射 (数字/布尔值要加引号)")
    return 表


def 读cat():
    关键词表 = _读yaml("keywords.yaml")
    图标表 = _读yaml("macos.yaml")
    缺 = sorted(set(关键词表.values()) - set(图标表))
    多余 = sorted(set(图标表) - set(关键词表.values()))
    if 缺 or 多余:
        raise ValueError(f"keywords 与 macos 对不上: 缺={缺} 多余={多余}")
    return 关键词表, 图标表


def 写python(关键词表, 图标表):
    段 = [
        '"""GENERATED by tools/build.py; 不要手改. 源: keywords.yaml + macos.yaml."""',
        "",
        "图标 = {",
    ]
    for 名, svg in 图标表.items():
        值 = repr(svg) if "'''" in svg or "\\" in svg else f"'''{svg}'''"
        段.append(f"    {名!r}: {值},")
    段 += ["}", "", "关键词 = {"]
    for 关键词, 名 in 关键词表.items():
        段.append(f"    {关键词!r}: {名!r},")
    段 += ["}", ""]
    _写(os.path.join("python", "cat", "_data.py"), "\n".join(段))


def _swift行(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def 写swift(关键词表, 图标表):
    for svg in 图标表.values():
        if '"""' in svg:
            raise ValueError("SVG 里含 Swift 多行串定界符: 需要改转义方式")
    段 = [
        "// GENERATED by tools/build.py; 不要手改. 源: keywords.yaml + macos.yaml.",
        "",
        "public let keywords: [String: String] = [",
    ]
    段 += [f'    "{_swift行(k)}": "{_swift行(v)}",' for k, v in 关键词表.items()]
    段 += ["]", "", "public let icons: [String: String] = ["]
    for 名, svg in 图标表.items():
        段.append(f'    "{_swift行(名)}": #"""')
        段.append(svg)
        段.append('"""#,')
    段 += ["]", ""]
    _写(os.path.join("swift", "Sources", "Cat", "Data.swift"), "\n".join(段))


def _写(相对路径, 内容):
    路径 = os.path.join(_根, 相对路径)
    os.makedirs(os.path.dirname(路径), exist_ok=True)
    with open(路径, "w", encoding="utf-8") as f:
        f.write(内容)
    print("wrote", 相对路径)


if __name__ == "__main__":
    写python(*读cat())
    写swift(*读cat())
